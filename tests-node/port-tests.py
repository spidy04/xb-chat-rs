# Copies the Node integration tests and points them at the Rust server.
# The assertions stay the same; only the setup changes. Re-run after the
# Node tests change:  python tests-node/port-tests.py
import re, pathlib
SRC = pathlib.Path(__file__).resolve().parents[2] / 'xb-chat' / 'test'
OUT = pathlib.Path(__file__).resolve().parent

def common(s):
    s = s.replace("'../clients/", "'../../xb-chat/clients/").replace("'../protocol/", "'../../xb-chat/protocol/")
    s = re.sub(r"import \{[^}]*\} from '\.\./server/[^']+';\n", "", s)
    s = s.replace("chat.store.", "await chat.store.")
    # `await f().x` awaits x; we need the property of the awaited result.
    s = re.sub(r"await chat\.store\.(\w+)\(([^()]*)\)\.(\w+)", r"(await chat.store.\1(\2)).\3", s)
    return "// GENERATED by port-tests.py from ../xb-chat/test: the Node tests, run against the Rust server.\n" + s

def sub(s, old, new):
    assert old in s, f"not found: {old[:80]!r}"
    return s.replace(old, new)

# ---------------------------------------------------------------- e2e
s = common((SRC / 'e2e.test.js').read_text(encoding='utf8'))
s = sub(s, "import { Client }", "import { startRust } from './rust.js';\nimport { Client }")
s = sub(s, """  const store = new Store({ dir, flushDelayMs: 5 });
  await store.load();
  media = new MediaServer({ dir: path.join(dir, 'media'), secret: 'test-secret' });
  await media.listen(0);
  chat = new ChatServer({ store, media, auth: [new PhoneAuth({ exposeCode: true }), new PasswordAuth({ store })], staticKeyPair: serverKey });
  await chat.listen(0);""", """  chat = await startRust({ dir, staticKeyPair: serverKey });
  media = chat.media;
  media.sweep = () => chat.store.expireMedia();""")
s = sub(s, "  await media.close();\n", "")
(OUT / 'e2e.test.js').write_text(s, encoding='utf8')

# ---------------------------------------------------------------- e2ee
s = common((SRC / 'e2ee.test.js').read_text(encoding='utf8'))
s = sub(s, "import { Client }", "import { startRust } from './rust.js';\nimport { Client }")
s = re.sub(r"  const store = new Store\(\{ dir, flushDelayMs: 60_000 \}\);.*?  media.publicUrl = base;\n",
"""  chat = await startRust({ dir });
  media = chat.media;
  base = chat.base;
  wsUrl = chat.wsUrl;
""", s, flags=re.S)
s = sub(s, "  await web.close();\n", "")
s = re.sub(r"async function serverSaw\(needle\) \{.*?\n\}\n", """async function serverSaw(needle) {
  return chat.store.saw(Buffer.from(needle).toString('base64'));
}
""", s, flags=re.S)
# The server records what it received (XB_TEST_ADMIN); serverSaw asks it.
s = sub(s, "    assert.ok(seenByServer.length > 0);\n", "")
# An account that never published keys: register over a raw transport
# (the Node test calls store.register directly).
s = sub(s, "await await chat.store.register('nokeys', 'password1');", """{
      const sock = net.connect(chat.port, '127.0.0.1');
      const t = new Transport(sock, { initiator: true, staticKeyPair: generateKeyPair() });
      t.on('error', () => {});
      await new Promise((r) => {
        t.once('ready', r);
        sock.once('connect', () => t.start());
      });
      const answered = new Promise((r) => t.once('node', r));
      t.send({ tag: 'auth', attrs: { mode: 'register', user: 'nokeys', pass: 'password1' } });
      assert.equal((await answered).tag, 'success');
      sock.destroy();
    }""")
(OUT / 'e2ee.test.js').write_text(s, encoding='utf8')

# ---------------------------------------------------------------- multidevice
s = common((SRC / 'multidevice.test.js').read_text(encoding='utf8'))
s = sub(s, "import { Client }", "import { startRust } from './rust.js';\nimport { Client }")
s = re.sub(r"  const store = new Store\(\{ dir, flushDelayMs: 60_000 \}\);.*?  await chat.listen\(0\);\n",
"""  chat = await startRust({ dir, env: { XB_FAKE_PUSH: '1', XB_LINK_TTL_MS: '300', XB_PUSH_COOLDOWN_MS: '300', XB_CODE_RESEND_MS: '200' } });
""", s, flags=re.S)
# The fake FCM lives in the Rust server (XB_FAKE_PUSH): ask it what it recorded.
s = re.sub(r"\bpushes(\.length|\[0\]|\.at\(-1\))", r"(await chat.store.pushes())\1", s)
s = sub(s, "[...await chat.store.devices.get('919800000601').values()][0].e2e", "(await chat.store.devices('919800000601'))[0].e2e")
(OUT / 'multidevice.test.js').write_text(s, encoding='utf8')

# ---------------------------------------------------------------- web
s = common((SRC / 'web.test.js').read_text(encoding='utf8'))
s = sub(s, "import { Client }", "import { startRust } from './rust.js';\nimport { Client }")
s = re.sub(r"  const store = new Store\(\{ dir \}\);.*?  media.publicUrl = base;\n",
"""  // Host the web app the way server/main.js does.
  chat = await startRust({ dir, appDir: path.resolve(import.meta.dirname, '../../xb-chat/clients/web') });
  media = chat.media;
  base = chat.base;
  wsUrl = chat.wsUrl;
""", s, flags=re.S)
s = sub(s, "  await web.close();\n", "")
s = s.replace("web.port", "chat.webPort")
(OUT / 'web.test.js').write_text(s, encoding='utf8')
print('ok')
